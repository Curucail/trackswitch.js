import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import wabtInit from "wabt";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fromRoot = (path) => resolve(rootDir, path);

/** Every WebAssembly kernel, and the constant its module exports. */
const kernels = [
	{
		sourcePath: "src/media/waveform-kernel.wat",
		targetPath: "src/generated/waveform-kernel.ts",
		name: "waveformKernelBase64",
		description: "The compiled waveform kernel, base64-encoded.",
	},
	{
		sourcePath: "src/media/spectrogram-kernel.wat",
		targetPath: "src/generated/spectrogram-kernel.ts",
		name: "spectrogramKernelBase64",
		description: "The compiled spectrogram kernel, base64-encoded.",
	},
];

const wabt = await wabtInit();
for (const { sourcePath, targetPath, name, description } of kernels) {
	const module = wabt.parseWat(
		sourcePath,
		readFileSync(fromRoot(sourcePath), "utf8"),
		{ simd: true, bulk_memory: true, sat_float_to_int: true },
	);
	module.validate();
	const { buffer } = module.toBinary({});
	module.destroy();

	const target = fromRoot(targetPath);
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(
		target,
		`// GENERATED by scripts/generate-kernels.mjs — do not edit.
// Run \`npm run kernel:build\` after changing ${sourcePath}.

/** ${description} */
export const ${name} =
	"${Buffer.from(buffer).toString("base64")}";
`,
	);
	console.log(`wrote ${targetPath}`);
}
