import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import wabtInit from "wabt";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fromRoot = (path) => resolve(rootDir, path);

const sourcePath = "src/media/waveform-kernel.wat";
const targetPath = "src/generated/waveform-kernel.ts";

const wabt = await wabtInit();
const module = wabt.parseWat(
	sourcePath,
	readFileSync(fromRoot(sourcePath), "utf8"),
	{ simd: true, bulk_memory: true },
);
module.validate();
const { buffer } = module.toBinary({});
module.destroy();

const target = fromRoot(targetPath);
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
	target,
	`// GENERATED by scripts/generate-waveform-kernel.mjs — do not edit.
// Run \`npm run kernel:build\` after changing ${sourcePath}.

/** The compiled waveform kernel, base64-encoded. */
export const waveformKernelBase64 =
	"${Buffer.from(buffer).toString("base64")}";
`,
);
console.log(`wrote ${targetPath}`);
