import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { extractCssTokens } from "./lib/css-tokens.mjs";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fromRoot = (path) => resolve(rootDir, path);

const groupTitles = {
	"src/css/parts/colors.css": "Colors",
	"src/css/parts/layout-tokens.css": "Layout and sizing",
};

function write(path, contents) {
	const target = fromRoot(path);
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, contents);
	console.log(`wrote ${path}`);
}

function renderTypeScript(tokens) {
	const entries = tokens
		.map((token) => `\t${JSON.stringify(token.name)},`)
		.join("\n");

	return `// GENERATED by scripts/generate-css-tokens.mjs — do not edit.
// Run \`npm run tokens:build\` after changing the root token declarations in
// src/css/parts/colors.css or src/css/parts/layout-tokens.css.

/** Every \`--ts-*\` custom property a config may override through a \`css\` block. */
export const cssTokens = [
${entries}
] as const;

export type TrackSwitchCssToken = (typeof cssTokens)[number];
`;
}

function renderMarkdown(tokens) {
	const sections = [];

	for (const [source, title] of Object.entries(groupTitles)) {
		const group = tokens.filter((token) => token.source === source);
		if (group.length === 0) {
			continue;
		}

		const rows = group
			.map((token) => `| \`${token.name}\` | \`${token.value}\` |`)
			.join("\n");
		sections.push(
			`#### ${title}\n\n| Token | Default |\n| --- | --- |\n${rows}`,
		);
	}

	return `<!-- GENERATED by scripts/generate-css-tokens.mjs — do not edit. -->\n\n${sections.join("\n\n")}\n`;
}

const tokens = extractCssTokens(rootDir);
if (tokens.length === 0) {
	throw new Error("Extracted no --ts-* tokens; the CSS scan is broken.");
}

write("src/generated/css-tokens.ts", renderTypeScript(tokens));
write("docs/_includes/css-tokens.md", renderMarkdown(tokens));
console.log(`${tokens.length} public --ts-* tokens`);
